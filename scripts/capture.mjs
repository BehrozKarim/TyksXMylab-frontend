import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto('http://127.0.0.1:5173/ward');
await page.getByRole('region', { name: 'Calendar year 2026 evidence', exact: true }).waitFor();
await page.screenshot({ path: 'test-results/ward-desktop.png', fullPage: true });
await page.screenshot({ path: 'test-results/ward-desktop-viewport.png' });
await page.getByRole('link', { name: 'Inspect evidence' }).click();
await page.getByRole('heading', { name: 'A change worth a closer look.' }).waitFor();
await page.screenshot({ path: 'test-results/investigation-desktop.png', fullPage: true });
await page.getByRole('tab', { name: 'Population context' }).click();
await page.screenshot({ path: 'test-results/investigation-composition.png', fullPage: true });
await page.setViewportSize({ width: 375, height: 812 });
await page.getByRole('link', { name: 'Back to ward overview' }).click();
await page.getByRole('region', { name: 'Calendar year 2026 evidence', exact: true }).waitFor();
await page.screenshot({ path: 'test-results/ward-mobile.png', fullPage: true });
await page.screenshot({ path: 'test-results/ward-mobile-viewport.png' });
await page.locator('.period-grid').screenshot({ path: 'test-results/ward-mobile-evidence.png' });
await page.getByRole('button', { name: 'Patient history', exact: true }).last().click();
await page.getByPlaceholder('Search, e.g. P-00142').fill('P-00142');
await page.getByRole('button', { name: 'P-00142 Synthetic patient' }).click();
await page.getByText('3 prior cultures').waitFor();
await page.screenshot({ path: 'test-results/history-mobile.png' });
console.log(JSON.stringify({ errors, screenshots: 'test-results/' }, null, 2));
await browser.close();
